def print_agent_cards():
    """Print agent role cards side by side."""
    cards = []
    for agent in AGENTS:
        tools_str = ", ".join(agent["tools"]) if agent["tools"] else "None"
        card = Panel(
            f"[bold {agent['color']}]{agent['emoji']} {agent['role']}[/bold {agent['color']}]\n\n"
            f"[bold]Goal:[/bold]\n{agent['goal']}\n\n"
            f"[bold]Backstory:[/bold]\n[dim]{agent['backstory'][:80]}...[/dim]\n\n"
            f"[bold]Tools:[/bold] [cyan]{tools_str}[/cyan]",
            title=f"Agent: {agent['name']}",
            border_style=agent["color"],
            width=30,
            padding=(1, 1),
        )
        cards.append(card)

    console.print(Columns(cards, padding=(0, 1)))


def run_crewai_demo():
    """Run the full CrewAI multi-agent demo."""

